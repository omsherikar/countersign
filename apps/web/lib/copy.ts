export type CopyId = keyof typeof copy;

export type CopyVars = Record<string, string | number>;

/** Look up a string by deck id and fill its {placeholders}. */
export function t(id: CopyId, vars?: CopyVars): string {
  const text: string = copy[id];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match));
}

/** Lookup for ids built at runtime from enum values, e.g. `type.${row.type}`. */
export function tk(id: string, vars?: CopyVars): string {
  if (id in copy) return t(id as CopyId, vars);
  return id;
}
